# ==========================================================
# Python Loops
# Covers:
# 1. for loop
# 2. while loop
# 3. break statement
# 4. continue statement
# 5. pass statement
# 6. nested loops
# ==========================================================

print("========================================")
print("           PYTHON LOOPS")
print("========================================")

# ----------------------------------------------------------
# 1. for loop
# ----------------------------------------------------------
print("\n1. for loop")
for i in range(1, 6):
    print(i)

# ----------------------------------------------------------
# 2. while loop
# ----------------------------------------------------------
print("\n2. while loop")
i = 1
while i <= 5:
    print(i)
    i += 1

# ----------------------------------------------------------
# 3. break statement
# ----------------------------------------------------------
print("\n3. break statement")
for i in range(1, 10):
    if i == 5:
        break
    print(i)

# ----------------------------------------------------------
# 4. continue statement
# ----------------------------------------------------------
print("\n4. continue statement")
for i in range(1, 6):
    if i == 3:
        continue
    print(i)

# ----------------------------------------------------------
# 5. pass statement
# ----------------------------------------------------------
print("\n5. pass statement")
for i in range(1, 4):
    if i == 2:
        pass
    print(i)

# ----------------------------------------------------------
# 6. nested loops
# ----------------------------------------------------------
print("\n6. nested loops")
for i in range(1, 4):
    for j in range(1, 4):
        print(f"i = {i}, j = {j}")

print("\n========================================")
print(" Loops Demonstration Completed!")
print("========================================")
